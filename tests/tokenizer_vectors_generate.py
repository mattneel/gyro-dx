rng = random.Random(1234)
pools = [
    "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ",
    "0123456789",
    "  \t\n\r\n",
    "!\"#$%&'()*+,-./:;<=>?@[\\]^_`{|}~",
    "éèêëàâäôöùûüçñßøåÅÉ",
    "αβγδεζηθικλμνξοπρστυφχψω",
    "你好世界日本語한국어漢字",
    "😀🎉🚀❤✨🇯🇵",
    "\u0301\u0308\u0303\u200d\u200b\u00a0\u3000\u2003",
    "'s't're've'm'll'd'S'RE",
    "<|im_start|>", "<|im_end|>", "<think>", "</think>",
]
fuzz = []
for _ in range(400):
    n = rng.randint(1, 60)
    s = []
    for _ in range(n):
        pool = rng.choice(pools)
        s.append(pool if pool.startswith("<") else "".join(rng.choice(pool) for _ in range(rng.randint(1, 5))))
    fuzz.append("".join(s))

texts = []
for t in fixed + fuzz:
    t = unicodedata.normalize("NFC", t)
    if t not in texts:
        texts.append(t)


def lit(b):
    out = []
    for c in b:
        if c in (0x22, 0x5C):
            out.append("\\" + chr(c))
        elif 0x20 <= c < 0x7F:
            out.append(chr(c))
        elif c == 0x0A:
            out.append("\\n")
        else:
            out.append("\\x%02x" % c)
    return '"' + "".join(out) + '"'


