    "emoji: 😀 🎉 👨‍👩‍👧‍👦 🇯🇵 ❤️ ✨ 🚀🚀🚀",
    "Café naïve résumé façade Übermensch señor Ångström Ελληνικά Русский текст עברית العربية हिन्दी ไทย",
