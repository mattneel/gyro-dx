w("// Generated by tests/tokenizer_vectors_generate.py (HF tokenizers reference). Do not edit.\n")
w("pub const Case = struct { text: []const u8, ids: []const u32 };\n")
w("pub const cases = [_]Case{\n")
for t in texts:
    ids = tok.encode(t, add_special_tokens=False).ids
    w("    .{ .text = %s, .ids = &.{ %s } },\n" % (lit(t.encode("utf-8")), ", ".join(map(str, ids))))
w("};\n")
