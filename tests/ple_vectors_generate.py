#!/usr/bin/env python3
"""Generate PLE vectors with an isolated C implementation of the upstream hash."""
import ctypes
import json
import os
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
MULTIPLIERS = [23703573157769, 20109073645365, 8052911324071]
OFFSETS = [0, 20000003, 40000026, 60000059, 80000106, 100000165, 120000228, 140000297,
           160000374, 180000455, 200000548, 220000655, 240000802, 260000955, 280001114, 300001275]
SIZES = [20000003, 20000023, 20000033, 20000047, 20000059, 20000063, 20000069, 20000077,
         20000081, 20000093, 20000107, 20000147, 20000153, 20000159, 20000161, 20000171]
CASES = [(1, [-1, -1]), (12345, [456, 789]), (248044, [456, 789]),
         (123, [248044, 555]), (123, [-1, 555]), (123, [555, 248044]),
         (248319, [248318, 248317]), (0, [0, 0])]

# The oracle expresses the formula in src/models/qwen4exp.cpp at the pinned revision.
# It executes outside the Zig module and produces fixed expected row IDs.
ORACLE = r"""
#include <stdint.h>
void rows(uint32_t token, const int32_t previous[2], const uint64_t multiplier[3],
          const uint64_t offset[16], const uint64_t size[16], uint64_t out[16]) {
    uint64_t context[3] = {token, 248044, 248044};
    int cut = 0;
    for (int index = 1; index < 3; ++index) {
        int32_t predecessor = cut ? -1 : previous[index - 1];
        cut = cut || predecessor < 0 || predecessor == 248044;
        context[index] = cut ? 248044 : (uint32_t)predecessor;
    }
    for (int n = 2; n <= 3; ++n) {
        uint64_t mixed = context[0] * multiplier[0];
        for (int j = 1; j < n; ++j) mixed ^= context[j] * multiplier[j];
        for (int g = 0; g < 8; ++g) {
            int h = (n - 2) * 8 + g;
            out[h] = mixed % size[h] + offset[h];
        }
    }
}
"""


def generate():
    with tempfile.TemporaryDirectory(prefix="ple-oracle-", dir=ROOT) as tmp:
        source = Path(tmp) / "ple.c"
        library = Path(tmp) / "ple.so"
        source.write_text(ORACLE)
        subprocess.run([os.environ.get("CC", "cc"), "-std=c11", "-O2", "-shared", "-fPIC",
                        str(source), "-o", str(library)], check=True)
        reference = ctypes.CDLL(str(library))
        array16 = ctypes.c_uint64 * 16
        multipliers = (ctypes.c_uint64 * 3)(*MULTIPLIERS)
        offsets = array16(*OFFSETS)
        sizes = array16(*SIZES)
        results = []
        for token, history in CASES:
            previous = (ctypes.c_int32 * 2)(*history)
            out = array16()
            reference.rows(ctypes.c_uint32(token), previous, multipliers, offsets, sizes, out)
            results.append(list(out))
        wrapping = (ctypes.c_uint64 * 3)(2**64 - 1, 2**64 - 17, 2**64 - 33)
        out = array16()
        reference.rows(ctypes.c_uint32(248319), (ctypes.c_int32 * 2)(248318, 248317), wrapping, offsets, sizes, out)
        wrap_result = list(out)
    def zig_array(values):
        return ".{ " + ", ".join(str(value) for value in values) + " }"
    lines = ["// Generated by tests/ple_vectors_generate.py from an isolated C oracle.",
             "pub const expected = [_][16]u64{"]
    lines += ["    " + zig_array(row) + "," for row in results]
    lines += ["};", "pub const wrapping: [16]u64 = " + zig_array(wrap_result) + ";", ""]
    (ROOT / "src/ple_vectors.zig").write_text("\n".join(lines))
    record = {"source": "https://gitlab.com/agentionai-group/llama.cpp/-/blob/9aa51ce4fdd3435a91531ffe16a17414ccc6dc6f/src/models/qwen4exp.cpp",
              "cases": [{"token": token, "history_newest_first": history, "rows": rows}
                        for (token, history), rows in zip(CASES, results)],
              "wrapping_multipliers": [2**64-1, 2**64-17, 2**64-33], "wrapping_rows": wrap_result}
    (ROOT / "tests/ple_vectors.json").write_text(json.dumps(record, indent=2) + "\n")
    print(f"Generated {len(CASES)} history cases and one wrapping arithmetic case.")


if __name__ == "__main__":
    generate()
