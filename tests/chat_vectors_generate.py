"""Regenerates src/chat_vectors.zig: renders conversations with Python jinja2 (HF-style sandboxed
environment: trim_blocks + lstrip_blocks) and the real GGUF chat template.

Setup:  pip install jinja2
Usage:  python tests/chat_vectors_generate.py chat_template.jinja > src/chat_vectors.zig
        (chat_template.jinja = raw bytes of the GGUF key tokenizer.chat_template)
"""
import json
import sys

from jinja2.exceptions import TemplateError
from jinja2.sandbox import ImmutableSandboxedEnvironment

src = open(sys.argv[1], encoding="utf-8", newline="").read()


def raise_exception(message):
    raise TemplateError(message)


env = ImmutableSandboxedEnvironment(trim_blocks=True, lstrip_blocks=True)
env.filters["tojson"] = lambda v, **kw: json.dumps(v, ensure_ascii=False)
env.globals["raise_exception"] = raise_exception
template = env.from_string(src)

U, A, S, T = "user", "assistant", "system", "tool"
scenarios = [
    ("system+user", [(S, "You are a helpful assistant."), (U, "Hello!")], {}),
    ("user only, thinking off", [(U, "What is 2+2?")], {"enable_thinking": False}),
    ("system+user, thinking off", [(S, "Be terse."), (U, "Hi")], {"enable_thinking": False}),
    ("multi-turn with reasoning", [
        (S, "  You are Gyro.  \n"), (U, "Question one"),
        (A, "Answer one", {"reasoning_content": "  step by step  \n"}),
        (U, "Question two"), (A, "Answer two", {"reasoning_content": "more thought"}), (U, "Question three"),
    ], {}),
    ("multi-turn, preserve_thinking=false", [
        (U, "q1"), (A, "a1", {"reasoning_content": "r1"}), (U, "q2"), (A, "a2", {"reasoning_content": "r2"}), (U, "q3"),
    ], {"preserve_thinking": False}),
    ("effort medium + low", [(S, "sys"), (U, "q")], {"reasoning_effort": "medium"}),
    ("effort low", [(U, "q")], {"reasoning_effort": "low"}),
    ("effort high alias", [(U, "q")], {"reasoning_effort": "high"}),
    ("developer + merged system", [("developer", "dev rules"), (S, "extra"), (S, "   "), (U, "go")], {}),
    ("tool calls and responses", [
        (S, "Use tools."), (U, "Weather in Paris and Rome?"),
        (A, "Checking.", {"tool_calls": [
            {"function": {"name": "get_weather", "arguments": {"city": "Paris"}}},
            {"function": {"name": "get_weather", "arguments": {"city": "Rome", "unit": "C"}}},
        ]}),
        (T, "sunny"), (T, "rainy\nwith newline"),
        (A, "", {"reasoning_content": "done", "tool_calls": [{"name": "noop", "arguments": {}}]}),
        (T, "ok"), (U, "thanks  "),
    ], {}),
    ("tool response as user turn", [
        (U, "run it"), (A, "", {"tool_calls": [{"name": "run", "arguments": {"cmd": "ls"}}]}),
        (U, "<tool_response>\nfile\n</tool_response>"),
    ], {}),
    ("no generation prompt", [(U, "hi"), (A, "hello")], {"add_generation_prompt": False}),
    ("unicode trim", [(U, "\u3000 héllo 日本 \u00a0"), (A, "\u2003ok\u2003")], {}),
    ("empty content", [(U, ""), (A, "")], {}),
]

ZIG_OPTS = {
    "enable_thinking": lambda v: ".enable_thinking = " + ("true" if v else "false"),
    "preserve_thinking": lambda v: ".preserve_thinking = " + ("true" if v else "false"),
    "add_generation_prompt": lambda v: ".add_generation_prompt = " + ("true" if v else "false"),
    "reasoning_effort": lambda v: '.reasoning_effort = "%s"' % v,
}


def lit(s):
    out = []
    for c in s.encode("utf-8"):
        if c in (0x22, 0x5C):
            out.append("\\" + chr(c))
        elif c == 0x0A:
            out.append("\\n")
        elif 0x20 <= c < 0x7F:
            out.append(chr(c))
        else:
            out.append("\\x%02x" % c)
    return '"' + "".join(out) + '"'


w = sys.stdout.write
w("// Generated by tests/chat_vectors_generate.py (Python jinja2 reference). Do not edit.\n")
w('const chat = @import("chat.zig");\n')
w("pub const Case = struct { name: []const u8, messages: []const chat.Message, options: chat.Options, expected: []const u8 };\n")
w("pub const cases = [_]Case{\n")
for name, msgs, opts in scenarios:
    jm, zm = [], []
    for m in msgs:
        role, content = m[0], m[1]
        extra = m[2] if len(m) > 2 else {}
        d = {"role": role, "content": content}
        d.update(extra)
        jm.append(d)
        fields = [".role = .%s" % role, ".content = %s" % lit(content)]
        if "reasoning_content" in extra:
            fields.append(".reasoning_content = %s" % lit(extra["reasoning_content"]))
        if "tool_calls" in extra:
            calls = []
            for tc in extra["tool_calls"]:
                f = tc.get("function", tc)
                args = ", ".join(".{ .name = %s, .value = %s }" % (lit(k), lit(v)) for k, v in f["arguments"].items())
                calls.append(".{ .name = %s, .arguments = &.{ %s } }" % (lit(f["name"]), args))
            fields.append(".tool_calls = &.{ %s }" % ", ".join(calls))
        zm.append(".{ %s }" % ", ".join(fields))
    kwargs = {"add_generation_prompt": True}
    kwargs.update(opts)
    expected = template.render(messages=jm, **kwargs)
    zopts = ", ".join(ZIG_OPTS[k](v) for k, v in opts.items())
    w("    .{\n        .name = %s,\n        .messages = &.{\n" % lit(name))
    for z in zm:
        w("            %s,\n" % z)
    w("        },\n        .options = .{ %s },\n        .expected = %s,\n    },\n" % (zopts, lit(expected)))
w("};\n")
