"""Regenerates src/unicode_tables.zig (letter/mark/number ranges) from Python's unicodedata.

Usage: python tests/unicode_tables_generate.py > src/unicode_tables.zig
"""
import sys
import unicodedata

CLASS = {"L": 1, "M": 2, "N": 3}
ranges = []
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    cls = CLASS.get(unicodedata.category(chr(cp))[0], 0)
    if cls == 0:
        continue
    if ranges and ranges[-1][1] + 1 == cp and ranges[-1][2] == cls:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp, cls])

out = sys.stdout
out.write("// Generated by tests/unicode_tables_generate.py from Unicode %s. Do not edit.\n" % unicodedata.unidata_version)
out.write("pub const Range = struct { lo: u21, hi: u21, class: u8 };\n")
out.write("/// class 1 = \\p{L}, 2 = \\p{M}, 3 = \\p{N}; sorted, non-overlapping.\n")
out.write("pub const ranges = [_]Range{\n")
for lo, hi, cls in ranges:
    out.write("    .{ .lo = 0x%X, .hi = 0x%X, .class = %d },\n" % (lo, hi, cls))
out.write("};\n")
